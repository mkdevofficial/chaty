-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. USERS TABLE
-- Preserves BIGINT id for 100% compatibility with Flutter app models,
-- SQLite local cache, and existing serializers.
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    phone TEXT UNIQUE,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    bio TEXT NOT NULL DEFAULT '',
    password_hash TEXT,
    avatar_url TEXT,
    avatar_file_id BIGINT,
    online BOOLEAN NOT NULL DEFAULT false,
    last_seen TIMESTAMPTZ,
    email TEXT UNIQUE,
    google_id TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);
CREATE INDEX IF NOT EXISTS idx_users_phone ON public.users(phone);
CREATE INDEX IF NOT EXISTS idx_users_auth_id ON public.users(auth_id);

-- 3. FOLLOWS TABLE
CREATE TABLE IF NOT EXISTS public.follows (
    follower_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    following_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (follower_id, following_id)
);

CREATE INDEX IF NOT EXISTS idx_follows_following ON public.follows(following_id);

-- 4. CONVERSATIONS TABLE
CREATE TABLE IF NOT EXISTS public.conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user1_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    user2_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_user_order CHECK (user1_id < user2_id),
    CONSTRAINT uq_conversation_pair UNIQUE (user1_id, user2_id)
);

CREATE INDEX IF NOT EXISTS idx_conversations_user1 ON public.conversations(user1_id);
CREATE INDEX IF NOT EXISTS idx_conversations_user2 ON public.conversations(user2_id);
CREATE INDEX IF NOT EXISTS idx_conversations_updated ON public.conversations(updated_at DESC);

-- 5. CONVERSATION READS TABLE
CREATE TABLE IF NOT EXISTS public.conversation_reads (
    conversation_id BIGINT NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    last_read_message_id BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (conversation_id, user_id)
);

-- 6. FILES TABLE (Metadata for uploads)
CREATE TABLE IF NOT EXISTS public.files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL, -- 'avatar', 'image', 'audio', 'file', 'story'
    storage_path TEXT NOT NULL,
    original_name TEXT,
    mime TEXT NOT NULL,
    size BIGINT NOT NULL,
    width INTEGER,
    height INTEGER,
    duration_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_files_owner ON public.files(owner_id);

-- 7. MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    client_id TEXT,
    type TEXT NOT NULL CHECK (type IN ('text', 'image', 'audio', 'file', 'sticker')),
    text TEXT,
    file_id BIGINT REFERENCES public.files(id) ON DELETE SET NULL,
    file_url TEXT,
    file_name TEXT,
    file_size BIGINT,
    mime_type TEXT,
    width INTEGER,
    height INTEGER,
    duration_ms INTEGER,
    sticker_pack TEXT,
    sticker_id TEXT,
    status TEXT NOT NULL DEFAULT 'sent' CHECK (status IN ('sent', 'delivered', 'read')),
    reply_to_id BIGINT REFERENCES public.messages(id) ON DELETE SET NULL,
    deleted_for_all BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_messages_conv_id ON public.messages(conversation_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_status ON public.messages(conversation_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_messages_client ON public.messages(conversation_id, sender_id, client_id) WHERE client_id IS NOT NULL;

-- 8. STORIES TABLE
CREATE TABLE IF NOT EXISTS public.stories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    type TEXT NOT NULL CHECK (type IN ('image', 'text')),
    file_id BIGINT REFERENCES public.files(id) ON DELETE SET NULL,
    media_url TEXT,
    caption TEXT,
    text TEXT,
    bg_color TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '24 hours')
);

CREATE INDEX IF NOT EXISTS idx_stories_user ON public.stories(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_stories_expires ON public.stories(expires_at);

-- 9. STORY VIEWS TABLE
CREATE TABLE IF NOT EXISTS public.story_views (
    story_id BIGINT NOT NULL REFERENCES public.stories(id) ON DELETE CASCADE,
    viewer_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (story_id, viewer_id)
);

