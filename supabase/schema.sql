-- 1. Trigger to automatically bump conversation updated_at when a message is inserted
CREATE OR REPLACE FUNCTION public.fn_update_conversation_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE public.conversations
    SET updated_at = NEW.created_at
    WHERE id = NEW.conversation_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_message_bump_conversation ON public.messages;
CREATE TRIGGER trg_message_bump_conversation
AFTER INSERT ON public.messages
FOR EACH ROW
EXECUTE FUNCTION public.fn_update_conversation_timestamp();

-- 2. Helper RPC: Get or create conversation between current user and peer
CREATE OR REPLACE FUNCTION public.get_or_create_conversation(p_user_a BIGINT, p_user_b BIGINT)
RETURNS JSONB AS $$
DECLARE
    v_u1 BIGINT;
    v_u2 BIGINT;
    v_conv_id BIGINT;
    v_created_at TIMESTAMPTZ;
    v_updated_at TIMESTAMPTZ;
BEGIN
    IF p_user_a < p_user_b THEN
        v_u1 := p_user_a;
        v_u2 := p_user_b;
    ELSE
        v_u1 := p_user_b;
        v_u2 := p_user_a;
    END IF;

    SELECT id, created_at, updated_at
    INTO v_conv_id, v_created_at, v_updated_at
    FROM public.conversations
    WHERE user1_id = v_u1 AND user2_id = v_u2;

    IF NOT FOUND THEN
        INSERT INTO public.conversations (user1_id, user2_id, created_at, updated_at)
        VALUES (v_u1, v_u2, NOW(), NOW())
        RETURNING id, created_at, updated_at INTO v_conv_id, v_created_at, v_updated_at;
    END IF;

    RETURN jsonb_build_object(
        'id', v_conv_id,
        'user1_id', v_u1,
        'user2_id', v_u2,
        'created_at', v_created_at,
        'updated_at', v_updated_at
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 3. Helper RPC: Mark conversation as read
CREATE OR REPLACE FUNCTION public.mark_conversation_read(p_conv_id BIGINT, p_user_id BIGINT)
RETURNS JSONB AS $$
DECLARE
    v_max_id BIGINT;
BEGIN
    SELECT COALESCE(MAX(id), 0) INTO v_max_id
    FROM public.messages
    WHERE conversation_id = p_conv_id;

    INSERT INTO public.conversation_reads (conversation_id, user_id, last_read_message_id, updated_at)
    VALUES (p_conv_id, p_user_id, v_max_id, NOW())
    ON CONFLICT (conversation_id, user_id)
    DO UPDATE SET
        last_read_message_id = EXCLUDED.last_read_message_id,
        updated_at = EXCLUDED.updated_at;

    UPDATE public.messages
    SET status = 'read'
    WHERE conversation_id = p_conv_id
      AND sender_id != p_user_id
      AND status != 'read';

    RETURN jsonb_build_object('ok', true, 'last_read_message_id', v_max_id);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

